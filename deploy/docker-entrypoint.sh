#!/bin/sh
# Точка входа контейнера: подготовить каталог файлов и сбросить права.
#
# Платформа монтирует постоянный диск в STORAGE_DIR (/app/storage) обычно от
# root — тогда процесс под пользователем node не смог бы туда писать, и
# загрузка SCORM-пакетов падала бы с EACCES. Поэтому стартуем root'ом, отдаём
# каталог пользователю node и только после этого запускаем приложение под ним.
set -e

STORAGE_DIR="${STORAGE_DIR:-/app/storage}"

if [ "$(id -u)" = "0" ]; then
  mkdir -p "$STORAGE_DIR"
  # Не критично, если диск не даёт менять владельца (например, сетевой):
  # тогда приложение сообщит о проблеме при первой записи.
  # Рекурсивно — только когда каталог ещё чужой (свежий диск или файлы,
  # залитые вручную), чтобы не обходить всё хранилище на каждом старте.
  if [ "$(stat -c %U "$STORAGE_DIR")" != "node" ]; then
    chown -R node:node "$STORAGE_DIR" 2>/dev/null \
      || echo "[entrypoint] не удалось сменить владельца $STORAGE_DIR" >&2
  fi
  exec setpriv --reuid=node --regid=node --init-groups "$@"
fi

exec "$@"
